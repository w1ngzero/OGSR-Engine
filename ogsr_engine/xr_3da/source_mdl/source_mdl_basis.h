#pragma once
//--------------------------------------------------------------------------------------------------
// source_mdl_basis.h -- единое изменение базиса системы координат: Source -> X-Ray (OGSR).
//
// ЗАЧЕМ:
//   Source (и модели из Garry's Mod) используют ЛЕВОстороннюю систему координат, оси Y-вверх.
//   X-Ray/OGSR использует ПРАВОстороннюю систему, Z-вверх.
//   Чистым поворотом левостороннюю раму в правостороннюю не перевести — нужна рефлексия,
//   которая к тому же меняет порядок (winding) треугольников и знак нормалей.
//
//   Чтобы скелет И меш были согласованы, применяется ОДИН И ТОТ ЖЕ базис слева ко всем
//   model-space трансформам костей и ко всем вершинам. Этот модуль — единственное место
//   определения базиса, чтобы скелет и меш никогда не разошлись.
//
// ВЫБРАННЫЙ БАЗИС (масштаб + ориентация, det = +1 — поворот без отражения):
//
//   МАСШТАБ. Source (Valve) единицы НЕ равны единицам X-Ray. Измерено по реальным моделям:
//     v_knife: клинок ~11 ед. вдоль Source Z;
//     gfl2_asteria_arms: пальцы тянутся ~24 ед. вдоль Source Z, размах ~52 ед. вдоль X.
//   Вьюмодель оружия X-Ray ~0.5..0.7 ед. Поэтому нужен масштаб S ≈ 0.05 (единственный
//   тюнинг под размер модели — поправь S при необходимости).
//
//   ОРИЕНТАЦИЯ. Оси Source-вьюмодели замерены на реальных файлах:
//     Source "вперёд" (куда смотрят пальцы/клинок) = +Z;  Source "вверх" = +Y.
//   Целевая конвенция X-Ray:  "вперёд" = +Y,  "вверх" = +Z.
//   Отсюда:  source.z -> xray.y ; source.y -> xray.z ; source.x -> xray.-x (поворот, det=+1).
//
//   Базис (out = M * in):
//     xray.x = -S * source.x
//     xray.y = +S * source.z
//     xray.z = +S * source.y
//   det(без масштаба) = +1 => треугольники не переворачиваются, нормали не меняют знак.
//
// Модуль разделён на "чистую" (standalone, ДЕТЕРМИНИРОВАННУЮ, тестируемую) часть и на
// движковый Fmatrix. Базовая математика читается через «обычные» координаты (столбцовый
// вектор: out = M * in), без опоры на неоднозначную ориентацию Fmatrix, поэтому она
// проверяется юнит-тестом на конкретных числах.
//
// ВАЖНО про движковую часть: X-Ray Fmatrix хранится row-major, а transform_tiny/mul_43 имеют
// собственную внутреннюю конвенцию. Проставление на-крест базиса в mul_43(basis, model) здесь
// делается консистентно для скелета и меша, но финальную on-screen сверку (и, при
// необходимости, поправку транспонирования) нужно провести на реальной модели в движке —
// это шаг верификации следующего раунда. Чистая математика при этом верна независимо от неё.
//--------------------------------------------------------------------------------------------------

#include <cstdint>
#include <cmath>

namespace SourceMdl
{
// ------------------------------------------------------------------------------------------------
// Чистая (безяжжевая) часть базиса. Работает на «обычных» координатах (out = M * in, 3x3).
// ------------------------------------------------------------------------------------------------
struct Basis3
{
    float m[3][3];
};

// Единственный тюнинг под масштаб: Source-единицы -> X-Ray-единицы.
// Измерено: v_knife клинок ~11 Source-ед., руки тянутся ~24 Source-ед. Вьюмодель X-Ray ~0.5..0.7.
// S = 0.05 даёт клинок ~0.55 ед. (разумная вьюмодель). Если модель всё ещё велика/мала — меняй S.
inline constexpr float kSourceToXRayScale = 0.05f;

// Базис Source -> X-Ray: масштаб + ориентация, det(поворотная часть) == +1.
inline Basis3 GetSourceToXRayBasis()
{
    // out = M * in, где M[строка][столбец]:
    //   out.x = -S * in.x
    //   out.y = +S * in.z
    //   out.z = +S * in.y
    Basis3 b{};
    b.m[0][0] = -kSourceToXRayScale; // xray.x = -S*source.x  (поворот: right -> -x)
    b.m[1][2] =  kSourceToXRayScale; // xray.y = +S*source.z  (source forward(z) -> +Y)
    b.m[2][1] =  kSourceToXRayScale; // xray.z = +S*source.y  (source up(y)  -> +Z)
    return b;
}

// Число-детерминант 3x3.
inline float Det3(const Basis3& b)
{
    return b.m[0][0] * (b.m[1][1] * b.m[2][2] - b.m[1][2] * b.m[2][1]) -
           b.m[0][1] * (b.m[1][0] * b.m[2][2] - b.m[1][2] * b.m[2][0]) +
           b.m[0][2] * (b.m[1][0] * b.m[2][1] - b.m[1][1] * b.m[2][0]);
}

struct Vec3f
{
    float x, y, z;
};

// out = M * in  (столбцовый вектор).
inline Vec3f Transform(const Basis3& b, const Vec3f& v)
{
    return {b.m[0][0] * v.x + b.m[0][1] * v.y + b.m[0][2] * v.z,
            b.m[1][0] * v.x + b.m[1][1] * v.y + b.m[1][2] * v.z,
            b.m[2][0] * v.x + b.m[2][1] * v.y + b.m[2][2] * v.z};
}

// Обязателен ли реверс winding/нормалей при этом базисе? det<0 => да.
inline bool RequiresWindingOrNormalFlip(const Basis3& b) { return Det3(b) < 0.0f; }

// ------------------------------------------------------------------------------------------------
// Движковая часть (нужен X-Ray): Fmatrix == тот же базис, готовый применяться к скелету/мешу.
// ------------------------------------------------------------------------------------------------
} // namespace SourceMdl
